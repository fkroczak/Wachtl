_INDEX: dict[str, str] = {p: vendor for vendor, prefixes in _DATA.items() for p in prefixes.split()}


def vendor(mac: str | None) -> str | None:
    """Hersteller zur MAC („AA:BB:CC:DD:EE:FF“, auch mit - oder ohne Trenner); None, wenn unbekannt."""
    if not mac:
        return None
    hexs = "".join(ch for ch in mac.upper() if ch in "0123456789ABCDEF")
    return _INDEX.get(hexs[:6]) if len(hexs) >= 6 else None
